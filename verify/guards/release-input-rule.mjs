// verify/guards/release-input-rule.mjs — guard for scripts/release-input-rule.mjs, the rule that tells
// `pnpm release:smoke` whether a flat input take fails the release or a synth take may stand in (D26).
//
// Imports the REAL module. Covers: every device-side path requires the input take; a looper-only or
// frontend-only diff does not; any difference in Cargo.toml beyond its [package] version line and line
// endings does (a flip under a crate's own profile table, an unrelated dependency); any cpal or asio-sys
// entry of Cargo.lock that differs, comes or goes does, the second of two included; an unrelated lock
// bump does not; a tree that is not clean does; no tag, no answer from git, or a missing part of the
// answer requires it (fail closed).
// Cannot see: the git calls that feed the rule (verify/guards/release-changes.mjs), or the smoke's two
// takes (the release run proves those).
// Run: node verify/guards/release-input-rule.mjs

import assert from 'node:assert';
import { inputTakeRule } from '../../scripts/release-input-rule.mjs';

let passed = 0;
let failed = 0;

function check(name, fn) {
  try {
    fn();
    passed++;
  } catch (e) {
    failed++;
    console.error(`FAIL: ${name}\n  ${e.message}`);
  }
}

const pkg = (name, version, deps = []) =>
  `[[package]]\nname = "${name}"\nversion = "${version}"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\n${deps.length ? `dependencies = [\n${deps.map((d) => ` "${d}",`).join('\n')}\n]\n` : ''}`;
const lock = (...packages) => `# This file is automatically @generated by Cargo.\nversion = 4\n\n${packages.join('\n')}`;
const LOCK = lock(pkg('asio-sys', '0.3.0', ['bindgen']), pkg('cpal', '0.18.1', ['asio-sys', 'windows']), pkg('serde', '1.0.200'));
/** A manifest shaped like the app's: the [package] version, dependency versions, cpal's own profile table. */
const manifest = ({ version = '0.5.2', serde = '1.0', overflow = 'false', tail = '' } = {}) =>
  `[package]\nname = "app"\nversion = "${version}"\nedition = "2021"\n\n[build-dependencies]\ntauri-build = { version = "2.6.2", features = [] }\n\n` +
  `[dependencies]\nserde = "${serde}"\ncpal             = { version = "=0.18.1", default-features = false }\n\n` +
  `[profile.release.package.cpal]\noverflow-checks = ${overflow}\n${tail}`;
const MANIFEST = manifest();
const since = (change) =>
  inputTakeRule({ base: 'v0.5.2', clean: true, dirty: [], paths: [], manifestBefore: MANIFEST, manifestAfter: MANIFEST, lockBefore: LOCK, lockAfter: LOCK, ...change });
const NOT_REQUIRED = { required: false, why: [] };

// ── Device-side paths ─────────────────────────────────────────────────────────────────────────────
for (const path of [
  'src-tauri/src/engine_io/cpal_driver.rs',
  'src-tauri/src/engine_io/midi/mod.rs',
  'src-tauri/src/host/clap.rs',
  'src-tauri/src/host/løkke.rs',
  'src-tauri/src/audio_output.rs',
  'src-tauri/src/asio_startup.rs',
]) {
  check(`${path} requires the input take and is named`, () => {
    const rule = since({ paths: ['src/ui/looper/Looper.tsx', path] });
    assert.strictEqual(rule.required, true);
    assert.deepStrictEqual(rule.why, [path]);
  });
}
check('a looper-only diff does not require it', () =>
  assert.deepStrictEqual(since({ paths: ['src-tauri/crates/lf-engine/src/looper.rs', 'src-tauri/crates/lf-engine/src/clock.rs'] }), NOT_REQUIRED));
check('a frontend-only diff does not require it', () =>
  assert.deepStrictEqual(since({ paths: ['src/ui/looper/Looper.tsx', 'src/app.css', 'package.json', 'docs/VERIFY.md'] }), NOT_REQUIRED));
check('other native files do not require it', () =>
  assert.strictEqual(since({ paths: ['src-tauri/src/update.rs', 'src-tauri/src/lib.rs', 'src-tauri/src/audio_input.rs', 'src-tauri/tauri.conf.json'] }).required, false));
check('a path that only starts like a device directory does not require it', () =>
  assert.strictEqual(since({ paths: ['src-tauri/src/host_notes.md', 'src-tauri/src/engine_io.md', 'docs/src-tauri/src/host/x.rs'] }).required, false));
check('no change at all does not require it', () => assert.deepStrictEqual(since({}), NOT_REQUIRED));

// ── Cargo.toml: any difference beyond the [package] version line and line endings ─────────────────
check('the overflow-checks flip under [profile.release.package.cpal] requires it and is quoted', () => {
  const rule = since({ paths: ['src-tauri/Cargo.toml'], manifestAfter: manifest({ overflow: 'true' }) });
  assert.strictEqual(rule.required, true);
  assert.strictEqual(rule.why.length, 1);
  assert.match(rule.why[0], /Cargo\.toml differs from v0\.5\.2/);
  assert.match(rule.why[0], /overflow-checks = true/);
});
check('a Cargo.toml whose only difference is the [package] version does not require it', () =>
  assert.deepStrictEqual(since({ paths: ['package.json', 'src-tauri/Cargo.toml', 'src-tauri/Cargo.lock', 'src-tauri/tauri.conf.json'], manifestAfter: manifest({ version: '0.5.3' }) }), NOT_REQUIRED));
check('the same Cargo.toml with CRLF line ends does not require it', () =>
  assert.deepStrictEqual(since({ manifestAfter: manifest({ version: '0.5.3' }).replace(/\n/g, '\r\n') }), NOT_REQUIRED));
check('an unrelated dependency line changed in Cargo.toml requires it (the conservative rule)', () => {
  const rule = since({ paths: ['src-tauri/Cargo.toml'], manifestAfter: manifest({ serde: '1.1' }) });
  assert.strictEqual(rule.required, true);
  assert.match(rule.why[0], /serde = "1\.1"/);
});
check('a dependency\'s version line is not the [package] version', () =>
  assert.strictEqual(since({ manifestAfter: MANIFEST.replace('version = "2.6.2"', 'version = "2.7.0"') }).required, true));
check('a version line under another table requires it', () =>
  assert.strictEqual(since({ manifestBefore: manifest({ tail: '\n[workspace.package]\nversion = "1"\n' }), manifestAfter: manifest({ tail: '\n[workspace.package]\nversion = "2"\n' }) }).required, true));
check('a line removed from Cargo.toml requires it', () =>
  assert.strictEqual(since({ manifestAfter: MANIFEST.replace('overflow-checks = false\n', '') }).required, true));
check('a version line added under another table requires it', () =>
  assert.strictEqual(since({ manifestAfter: MANIFEST.replace('[build-dependencies]\n', '[build-dependencies]\nversion = "9"\n') }).required, true));

// ── Cargo.lock: every cpal and asio-sys entry, whole ──────────────────────────────────────────────
check('a cpal version bump in Cargo.lock requires it', () => {
  const after = lock(pkg('asio-sys', '0.3.0', ['bindgen']), pkg('cpal', '0.18.2', ['asio-sys', 'windows']), pkg('serde', '1.0.200'));
  const rule = since({ paths: ['src-tauri/Cargo.lock'], lockAfter: after });
  assert.strictEqual(rule.required, true);
  assert.match(rule.why.join(' '), /cpal or asio-sys entry of src-tauri\/Cargo\.lock/);
});
check('an asio-sys version bump in Cargo.lock requires it', () => {
  const after = lock(pkg('asio-sys', '0.4.0', ['bindgen']), pkg('cpal', '0.18.1', ['asio-sys', 'windows']), pkg('serde', '1.0.200'));
  assert.strictEqual(since({ paths: ['src-tauri/Cargo.lock'], lockAfter: after }).required, true);
});
check('a changed dependency list under cpal requires it', () => {
  const after = lock(pkg('asio-sys', '0.3.0', ['bindgen']), pkg('cpal', '0.18.1', ['asio-sys', 'windows 0.62.0']), pkg('serde', '1.0.200'));
  assert.strictEqual(since({ lockAfter: after }).required, true);
});
check('with two cpal entries, a change in the SECOND alone requires it', () => {
  const two = (second) => lock(pkg('asio-sys', '0.3.0', ['bindgen']), pkg('cpal', '0.15.3', ['windows']), pkg('cpal', second, ['asio-sys', 'windows']), pkg('serde', '1.0.200'));
  assert.deepStrictEqual(since({ lockBefore: two('0.18.1'), lockAfter: two('0.18.1') }), NOT_REQUIRED);
  assert.strictEqual(since({ lockBefore: two('0.18.1'), lockAfter: two('0.18.2') }).required, true);
});
check('a second cpal entry added requires it', () => {
  const after = lock(pkg('asio-sys', '0.3.0', ['bindgen']), pkg('cpal', '0.18.1', ['asio-sys', 'windows']), pkg('cpal', '0.19.0', ['windows']), pkg('serde', '1.0.200'));
  assert.strictEqual(since({ lockAfter: after }).required, true);
});
check('cpal leaving Cargo.lock requires it', () => assert.strictEqual(since({ lockAfter: lock(pkg('serde', '1.0.200')) }).required, true));
check('an unrelated Cargo.lock bump does not require it', () => {
  const after = lock(pkg('asio-sys', '0.3.0', ['bindgen']), pkg('cpal', '0.18.1', ['asio-sys', 'windows']), pkg('serde', '1.0.219'));
  assert.deepStrictEqual(since({ paths: ['src-tauri/Cargo.lock'], lockAfter: after }), NOT_REQUIRED);
});
check('the same Cargo.lock with CRLF line ends does not require it', () =>
  assert.deepStrictEqual(since({ lockAfter: LOCK.replace(/\n/g, '\r\n') }), NOT_REQUIRED));
check('a crate whose name only contains cpal does not require it', () =>
  assert.deepStrictEqual(since({ lockAfter: `${LOCK}\n${pkg('cpal-extras', '1.0.0')}\n${pkg('my-asio-sys', '2.0.0')}` }), NOT_REQUIRED));

// ── The working tree ──────────────────────────────────────────────────────────────────────────────
check('a dirty tree requires it, says to commit first and names the entries', () => {
  const rule = since({ clean: false, dirty: ['?? src-tauri/src/engine_io/new.rs', ' M README.md'] });
  assert.strictEqual(rule.required, true);
  assert.strictEqual(rule.why.length, 1);
  assert.match(rule.why[0], /not clean/);
  assert.match(rule.why[0], /commit first/);
  assert.match(rule.why[0], /\?\? src-tauri\/src\/engine_io\/new\.rs/);
});
check('a dirty tree requires it beside a device-side path, each with its reason', () => {
  const rule = since({ clean: false, paths: ['src-tauri/src/audio_output.rs'] });
  assert.strictEqual(rule.why.length, 2);
  assert.ok(rule.why.includes('src-tauri/src/audio_output.rs'));
});

// ── Fail closed ───────────────────────────────────────────────────────────────────────────────────
check('no tag requires it', () => {
  const rule = since({ base: null });
  assert.strictEqual(rule.required, true);
  assert.match(rule.why[0], /no release tag/);
});
check('no answer from git requires it', () => {
  const rule = inputTakeRule({ base: 'v0.5.2', paths: null });
  assert.strictEqual(rule.required, true);
  assert.match(rule.why[0], /git gave no answer.*v0\.5\.2/);
});
for (const missing of ['clean', 'manifestBefore', 'manifestAfter', 'lockBefore', 'lockAfter']) {
  check(`an answer without ${missing} requires it`, () => {
    assert.strictEqual(since({ [missing]: undefined }).required, true);
    assert.strictEqual(since({ [missing]: null }).required, true);
  });
}

// ── Layouts a line-based reading could be fooled by ────────────────────────────────────────────────
check('a blank line inside a cpal entry does not hide its version change', () => {
  const spaced = (version) => lock(pkg('asio-sys', '0.3.0', ['bindgen']), pkg('cpal', version, ['asio-sys', 'windows']).replace('name = "cpal"\n', 'name = "cpal"\n\n'), pkg('serde', '1.0.200'));
  const rule = since({ lockBefore: spaced('0.18.1'), lockAfter: spaced('0.18.2') });
  assert.strictEqual(rule.required, true);
  assert.match(rule.why[0], /cpal or asio-sys entry of src-tauri\/Cargo\.lock/);
});
check('the same lock with a blank line inside the cpal entry, unchanged, does not require it', () => {
  const spaced = LOCK.replace('name = "cpal"\n', 'name = "cpal"\n\n');
  assert.deepStrictEqual(since({ lockBefore: LOCK, lockAfter: LOCK.replace('0.18.1', '0.18.1') }), NOT_REQUIRED);
  assert.deepStrictEqual(since({ lockBefore: spaced, lockAfter: spaced }), NOT_REQUIRED);
});
const FAKE_TABLE = (version) => `[dependencies.rubato]\nnotes = """\n[package]\n"""\nversion = "${version}"\n`;
check('a multi-line string that looks like a [package] header does not hide a dependency version', () => {
  const rule = since({ manifestBefore: manifest({ tail: FAKE_TABLE('1.0') }), manifestAfter: manifest({ tail: FAKE_TABLE('2.0') }) });
  assert.strictEqual(rule.required, true);
  assert.match(rule.why[0], /Cargo\.toml differs/);
});
check('a manifest with a multi-line string is compared whole: even its [package] version bump requires it', () => {
  const rule = since({ manifestBefore: manifest({ version: '0.5.2', tail: FAKE_TABLE('1.0') }), manifestAfter: manifest({ version: '0.6.0', tail: FAKE_TABLE('1.0') }) });
  assert.strictEqual(rule.required, true);
});

console.log(`=== RESULT: ${passed}/${passed + failed} checks passed, ${failed} failed ===`);
process.exit(failed === 0 ? 0 : 1);
