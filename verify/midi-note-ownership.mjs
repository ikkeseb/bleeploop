// Actual MIDI parser/router with two virtual Web MIDI ports. No hardware/native claims.
import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true, args: ['--autoplay-policy=no-user-gesture-required'] });
try {
  const page = await browser.newPage();
  await page.addInitScript(() => {
    const inputs = new Map(['a', 'b'].map((id) => [id, { id, name: `Probe ${id}`, state: 'connected', onmidimessage: null }]));
    const access = { inputs, onstatechange: null };
    window.__probeMidi = access;
    Object.defineProperty(navigator, 'requestMIDIAccess', { configurable: true, value: async () => access });
  });
  await page.goto(process.argv.find((arg) => arg.startsWith('--url='))?.slice(6) ?? 'http://localhost:1420');
  await page.waitForFunction(() => !!window.__lf && !!window.__probeMidi.inputs.get('a').onmidimessage);
  const result = await page.evaluate(async () => {
    const lf = window.__lf; await lf.engine.start();
    lf.selectSynth(0, 'organ'); lf.setActiveSlot(0);
    const pause = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
    await pause(150); lf.ensureActive();
    const access = window.__probeMidi;
    const send = (port, bytes) => access.inputs.get(port).onmidimessage({ data: Uint8Array.from(bytes) });
    send('a', [0x90, 60, 100]); send('b', [0x90, 60, 100]); send('a', [0x80, 60, 0]);
    const heldAfterFirstPortRelease = [...lf.inputRouter.held];
    lf.inputRouter.allNotesOff();
    send('a', [0x90, 60, 100]); send('a', [0x91, 60, 100]); send('a', [0x80, 60, 0]);
    const heldAfterFirstChannelRelease = [...lf.inputRouter.held];
    lf.inputRouter.allNotesOff();
    const analyser = lf.engine.ctx.createAnalyser(); analyser.fftSize = 4096;
    lf.engine.instrumentBus.connect(analyser);
    const data = new Float32Array(analyser.fftSize);
    const rms = () => {
      analyser.getFloatTimeDomainData(data);
      return Math.sqrt(data.reduce((sum, sample) => sum + sample * sample, 0) / data.length);
    };
    send('a', [0xb0, 64, 127]);
    send('b', [0x90, 67, 100]); await pause(120); send('b', [0x80, 67, 0]); await pause(250);
    const otherPortReleaseRms = rms();
    send('a', [0x90, 67, 100]); await pause(120); send('a', [0x80, 67, 0]);
    send('b', [0xb0, 64, 0]); await pause(250);
    const otherPedalUpRms = rms();
    send('a', [0xb0, 64, 0]); await pause(250);
    const ownPedalUpRms = rms();
    send('a', [0x90, 60, 100]); send('b', [0x90, 60, 100]);
    send('a', [0xb0, 123, 0]);
    const heldAfterOtherCc123 = [...lf.inputRouter.held];
    send('b', [0xb0, 123, 0]);
    const heldAfterBothCc123 = [...lf.inputRouter.held];
    await pause(250);
    send('a', [0xb0, 64, 127]); send('a', [0x90, 67, 100]); await pause(120);
    send('a', [0xb0, 123, 0]); await pause(250);
    const cc123UnderPedalRms = rms();
    send('a', [0xb0, 64, 0]); await pause(250);
    const cc123PedalUpRms = rms();
    send('a', [0xb0, 64, 127]);
    send('b', [0x90, 60, 100]);
    access.inputs.get('a').state = 'disconnected'; access.onstatechange();
    const heldAfterOtherDisconnect = [...lf.inputRouter.held];
    send('b', [0x80, 60, 0]); await pause(250);
    lf.inputRouter.handle({ type: 'on', note: 67, velocity: 100, source: 'computer' });
    await pause(150);
    lf.inputRouter.handle({ type: 'off', note: 67, velocity: 0, source: 'computer' });
    await pause(450);
    const releasedKeyboardRms = rms();
    lf.inputRouter.setSustain(false); lf.inputRouter.allNotesOff(); lf.engine.instrumentBus.disconnect(analyser);
    const key = document.querySelector('.kb__key[data-note="60"]');
    if (!key) throw new Error('pointer ownership test requires the visible keyboard');
    const capture = key.setPointerCapture;
    key.setPointerCapture = () => {}; // synthetic events cannot acquire browser-native pointer capture
    const pointer = (type, pointerId) => key.dispatchEvent(new PointerEvent(type, { bubbles: true, pointerId, pointerType: 'touch' }));
    pointer('pointerdown', 901); pointer('pointerdown', 902); await pause(30);
    pointer('pointerup', 901); await pause(30);
    const firstPointerUp = { held: [...lf.inputRouter.held], highlighted: key.classList.contains('kb__key--down') };
    pointer('pointerup', 902); await pause(30);
    const lastPointerUp = { held: [...lf.inputRouter.held], highlighted: key.classList.contains('kb__key--down') };
    key.setPointerCapture = capture;
    return { heldAfterFirstPortRelease, heldAfterFirstChannelRelease, releasedKeyboardRms, otherPortReleaseRms, otherPedalUpRms, ownPedalUpRms, heldAfterOtherCc123, heldAfterBothCc123, cc123UnderPedalRms, cc123PedalUpRms, heldAfterOtherDisconnect, firstPointerUp, lastPointerUp };
  });
  console.log(JSON.stringify(result));
  assert.deepEqual(result.firstPointerUp, { held: [60], highlighted: true }, 'first pointer release preserves sound and key highlight');
  assert.deepEqual(result.lastPointerUp, { held: [], highlighted: false }, 'last pointer releases sound and key highlight');
  assert.deepEqual(result.heldAfterFirstPortRelease, [60], 'one MIDI port must not release another port\'s held note');
  assert.deepEqual(result.heldAfterFirstChannelRelease, [60], 'one MIDI channel must not release another channel\'s held note');
  assert.ok(result.otherPortReleaseRms < 1e-5, 'one port pedal must not sustain another port');
  assert.ok(result.otherPedalUpRms > 0.01, 'unrelated pedal-up must preserve a sustained note');
  assert.ok(result.ownPedalUpRms < 1e-5, 'own pedal-up must release the note');
  assert.deepEqual(result.heldAfterOtherCc123, [60], 'CC123 must leave the other owner held');
  assert.deepEqual(result.heldAfterBothCc123, [], 'CC123 must release its own keys');
  assert.ok(result.cc123UnderPedalRms > 0.01, 'CC123 honors the physical pedal');
  assert.ok(result.cc123PedalUpRms < 1e-5, 'pedal-up completes a deferred CC123 release');
  assert.deepEqual(result.heldAfterOtherDisconnect, [60], 'unplugging one port must preserve the other port');
  assert.ok(result.releasedKeyboardRms < 1e-5, 'disconnecting a pedal controller must not leave future keyboard notes sustained forever');
} finally { await browser.close(); }
